/**
 * Custom Worker entry around the OpenNext handler (documented OpenNext
 * "custom worker" pattern). It adds what the shared kikkey.com zone settings
 * do not guarantee for this demo, without touching the zone:
 *
 * - an http → https upgrade (the zone does not force HTTPS);
 * - hygiene and security headers on EVERY Worker response, including the
 *   trailing-slash 308s and 404s that bypass next.config `headers()`.
 *
 * Static files served straight from Workers assets get the same headers
 * from public/_headers.
 */
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore -- generated by `opennextjs-cloudflare build`
import handler from "./.open-next/worker.js"

type WorkerContext = { waitUntil(promise: Promise<unknown>): void; passThroughOnException(): void }
type OpenNextHandler = { fetch(request: Request, env: unknown, ctx: WorkerContext): Promise<Response> }

const LOCAL_HOSTS = new Set(["localhost", "127.0.0.1", "[::1]"])

const HYGIENE: Record<string, string> = {
  "X-Robots-Tag": "noindex, nofollow, noarchive",
  "X-Content-Type-Options": "nosniff",
  "Referrer-Policy": "no-referrer",
}

const worker = {
  async fetch(request: Request, env: unknown, ctx: WorkerContext): Promise<Response> {
    const url = new URL(request.url)

    if (url.protocol === "http:" && !LOCAL_HOSTS.has(url.hostname)) {
      url.protocol = "https:"
      const safe = request.method === "GET" || request.method === "HEAD"
      return new Response(null, {
        status: safe ? 301 : 308,
        headers: { Location: url.toString(), ...HYGIENE },
      })
    }

    const response = await (handler as OpenNextHandler).fetch(request, env, ctx)
    const headers = new Headers(response.headers)
    for (const [key, value] of Object.entries(HYGIENE)) {
      if (!headers.has(key)) headers.set(key, value)
    }
    if (url.protocol === "https:") {
      headers.set("Strict-Transport-Security", "max-age=31536000")
    }
    return new Response(response.body, { status: response.status, statusText: response.statusText, headers })
  },
}

export default worker
